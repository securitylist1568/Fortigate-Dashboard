import { FeedKind } from './feeds.manifest';

export interface EntryMetaInfo {
  lineNumber: number;
  comment: string | null;
}

export interface ParsedFeedStats {
  count: number;
  bytes: number;
  headerCount: number | null;
  headerMismatch: boolean;
  internalLeakCount: number; // Count of internal/private IPs leaked into external blocklists
  entriesSet: Set<string>;   // Used strictly in-memory on server for deduplication, never serialized!
  entryMetaMap: Map<string, EntryMetaInfo>;
}

export interface ParsedCidrRange {
  cidr: string;
  netInt: number;
  maskInt: number;
}

const IPV4_REGEX = /^(?:(?:25[0-5]|2[0-4]\d|1\d\d|[1-9]?\d)\.){3}(?:25[0-5]|2[0-4]\d|1\d\d|[1-9]?\d)$/;

/**
 * Converts a valid IPv4 string to an unsigned 32-bit integer, or returns null if invalid.
 */
export function ipv4ToUint32(ip: string): number | null {
  const trimmed = ip.trim();
  if (!IPV4_REGEX.test(trimmed)) return null;
  const [a, b, c, d] = trimmed.split('.').map(Number);
  return (((a << 24) >>> 0) + ((b << 16) >>> 0) + ((c << 8) >>> 0) + d) >>> 0;
}

/**
 * Parses a CIDR string (e.g. "203.0.113.0/24") into unsigned 32-bit network and mask integers.
 */
export function parseCidrRange(entry: string): ParsedCidrRange | null {
  const parts = entry.trim().split('/');
  if (parts.length !== 2) return null;
  const ipInt = ipv4ToUint32(parts[0]);
  const prefix = Number(parts[1]);
  if (ipInt === null || !Number.isInteger(prefix) || prefix < 0 || prefix > 32) {
    return null;
  }
  const maskInt = prefix === 0 ? 0 : ((0xffffffff << (32 - prefix)) >>> 0);
  const netInt = (ipInt & maskInt) >>> 0;
  return { cidr: entry.trim(), netInt, maskInt };
}

/**
 * Checks whether an IPv4 string belongs to internal protected /16 subnet or RFC1918 private/loopback ranges
 * to verify that external blocklists have zero internal mis-blocks.
 */
export function isCampusOrPrivateIPv4(ip: string): boolean {
  if (!IPV4_REGEX.test(ip)) return false;
  const parts = ip.split('.').map(Number);
  const [a, b] = parts;
  if (a === 140 && b === 122) return true;
  if (a === 10 || a === 127 || a === 0) return true;
  if (a === 172 && b >= 16 && b <= 31) return true;
  if (a === 192 && b === 168) return true;
  return false;
}

const BOILERPLATE_COMMENT_REGEX =
  /^#+\s*(?:Generated by|Mode:|TZ:|Jobs:|Note:|Rules:|Count:|將要跳過封鎖|範例：|ncloud_|g-BLACK_|emailsys_|ntech_|===|---)/i;

/**
 * Parses a raw feed file content into summary statistics.
 * Handles CRLF/LF normalization, strips # comments (including inline comments),
 * extracts `# Count: <num>` header if present, and records line numbers & comment notes.
 */
export function parseFeedContent(
  rawText: string,
  kind: FeedKind,
  checkInternalLeak: boolean = false
): ParsedFeedStats {
  const bytes = Buffer.byteLength(rawText, 'utf8');
  const entryMetaMap = new Map<string, EntryMetaInfo>();

  if (kind === 'html') {
    const trimmed = rawText.trim();
    return {
      count: trimmed.length > 0 ? 1 : 0,
      bytes,
      headerCount: null,
      headerMismatch: false,
      internalLeakCount: 0,
      entriesSet: new Set<string>(),
      entryMetaMap,
    };
  }

  const normalized = rawText.replace(/\r\n/g, '\n').replace(/\r/g, '\n');
  const lines = normalized.split('\n');

  let headerCount: number | null = null;
  const entriesSet = new Set<string>();
  let validLineCount = 0;
  let internalLeakCount = 0;
  let pendingComments: string[] = [];
  let activeSectionComment: string | null = null;

  for (let i = 0; i < lines.length; i++) {
    const lineNum = i + 1;
    const trimmed = lines[i].trim();
    if (!trimmed) {
      pendingComments = [];
      continue;
    }

    if (trimmed.startsWith('#')) {
      const m = trimmed.match(/^#\s*Count\s*:\s*(\d+)/i);
      if (m) {
        headerCount = parseInt(m[1], 10);
      }
      const cleanedComment = trimmed.replace(/^#+\s*/, '').trim();
      if (
        cleanedComment &&
        !BOILERPLATE_COMMENT_REGEX.test(trimmed) &&
        !IPV4_REGEX.test(cleanedComment)
      ) {
        pendingComments.push(cleanedComment);
        if (pendingComments.length > 3) {
          pendingComments.shift();
        }
        activeSectionComment = pendingComments.join(' | ');
      }
      continue;
    }

    // Check inline comment if any
    let inlineComment: string | null = null;
    const hashIdx = trimmed.indexOf('#');
    if (hashIdx > 0) {
      inlineComment = trimmed.slice(hashIdx + 1).trim() || null;
    }

    // Strip inline comments or trailing descriptions
    const token = trimmed.split(/\s+#|\s+/)[0].trim();
    if (!token) continue;

    validLineCount += 1;
    entriesSet.add(token);

    if (!entryMetaMap.has(token)) {
      entryMetaMap.set(token, {
        lineNumber: lineNum,
        comment: inlineComment ?? activeSectionComment,
      });
    }
    pendingComments = [];

    if (checkInternalLeak && kind === 'ip') {
      const bareIp = token.split('/')[0];
      if (isCampusOrPrivateIPv4(bareIp)) {
        internalLeakCount += 1;
      }
    }
  }

  const headerMismatch = headerCount !== null && headerCount !== validLineCount;

  return {
    count: validLineCount,
    bytes,
    headerCount,
    headerMismatch,
    internalLeakCount,
    entriesSet,
    entryMetaMap,
  };
}
