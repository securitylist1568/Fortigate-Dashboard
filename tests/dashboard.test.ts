import { describe, it, expect } from 'vitest';
import { parseFeedContent, isCampusOrPrivateIPv4 } from '../src/lib/parsers';
import {
  parseLongTermCommitTitle,
  buildLongTermTrend,
  evaluatePipelineHealth,
} from '../src/lib/trend';
import {
  encryptSnapshotPayload,
  decryptSnapshotPayloadNode,
} from '../src/lib/vault-crypto';
import { computeSnapshotFromRawInputs } from '../src/lib/cti-fetcher';
import { FEEDS_MANIFEST } from '../src/lib/feeds.manifest';

describe('Feed Parser & Sanitization Verification', () => {
  it('handles CRLF, empty lines, # comments, inline comments, and trailing line without newline', () => {
    const raw =
      '# g-BLACK_IP_AutoLongTerm-v1.txt\r\n' +
      '# Generated by ncloud_longterm_block_v1_0.py\r\n' +
      '# Count: 3\r\n' +
      '\r\n' +
      '1.2.3.4\r\n' +
      '5.6.7.8 # inline note\n' +
      '9.10.11.12';

    const parsed = parseFeedContent(raw, 'ip', true);
    expect(parsed.count).toBe(3);
    expect(parsed.headerCount).toBe(3);
    expect(parsed.headerMismatch).toBe(false);
    expect(parsed.internalLeakCount).toBe(0);
    expect(parsed.entriesSet.has('5.6.7.8')).toBe(true);
  });

  it('handles 0-entry file with header comments (e.g. ncloud_block_dst_topn.txt)', () => {
    const raw =
      '# ncloud_block_dst_topn.txt\n# Generated by ncloud_topn_feed_push_v4_5.py\n#\n';
    const parsed = parseFeedContent(raw, 'ip', true);
    expect(parsed.count).toBe(0);
    expect(parsed.headerCount).toBeNull();
    expect(parsed.headerMismatch).toBe(false);
  });

  it('detects header count mismatch accurately', () => {
    const raw = '# Count: 10\n8.8.8.8\n1.1.1.1\n';
    const parsed = parseFeedContent(raw, 'ip', true);
    expect(parsed.count).toBe(2);
    expect(parsed.headerCount).toBe(10);
    expect(parsed.headerMismatch).toBe(true);
  });

  it('detects campus (140.122.0.0/16) and RFC1918 private IPs if leaked into external blocklist', () => {
    expect(isCampusOrPrivateIPv4('140.122.66.124')).toBe(true);
    expect(isCampusOrPrivateIPv4('192.168.1.1')).toBe(true);
    expect(isCampusOrPrivateIPv4('195.96.138.34')).toBe(false);
  });
});

describe('Commit Trend & Pipeline Health Parser', () => {
  it('accepts both v1.0 and v1.0.1 longterm commit titles and ignores fix:/feat: commits', () => {
    const v10 = parseLongTermCommitTitle(
      'feed(longterm v1.0): update g-BLACK_IP_AutoLongTerm-v1.txt (total=15651 added=9974 removed=0)'
    );
    expect(v10).toEqual({ total: 15651, added: 9974, removed: 0 });

    const v101 = parseLongTermCommitTitle(
      'feed(longterm v1.0.1): update g-BLACK_IP_AutoLongTerm-v1.txt (total=58144 added=2 removed=0)'
    );
    expect(v101).toEqual({ total: 58144, added: 2, removed: 0 });

    const nonData = parseLongTermCommitTitle(
      'docs: sync README.md and AGENTS.md ground rules'
    );
    expect(nonData).toBeNull();
  });

  it('evaluates pipeline health thresholds correctly (30m for 10m jobs, 540m for 3h longterm)', () => {
    const nowMs = Date.parse('2026-11-06T08:30:00Z');
    const commits = [
      {
        sha: '1111111111abcdef',
        commit: {
          message: 'feed(py v4.5): union(daily topn + 10m incremental)',
          committer: { date: '2026-11-06T08:25:00Z' }, // 5 mins ago -> healthy
        },
      },
      {
        sha: '2222222222abcdef',
        commit: {
          message:
            'feed(longterm v1.0.1): update g-BLACK_IP_AutoLongTerm-v1.txt (total=58144 added=2 removed=0)',
          committer: { date: '2026-11-06T04:08:00Z' }, // 262 mins ago (<540m) -> healthy
        },
      },
    ];
    const health = evaluatePipelineHealth(commits, nowMs);
    const topnHealth = health.find((h) => h.id === 'topn')!;
    const ltHealth = health.find((h) => h.id === 'longterm')!;
    expect(topnHealth.status).toBe('healthy');
    expect(ltHealth.status).toBe('healthy');
  });
});

describe('AES-256-GCM Security Vault Crypto & Zero-IP Leak Contract', () => {
  it('encrypts and decrypts snapshot payload losslessly and rejects wrong passkey', () => {
    const rawFilesById: Record<string, string> = {};
    for (const def of FEEDS_MANIFEST) {
      rawFilesById[def.id] = '195.96.138.34\n203.0.113.5\n';
    }
    const snapshot = computeSnapshotFromRawInputs({
      repo: 'securitylist1568/Fortigate',
      headSha: 'fa80149c2e1234567890',
      headTimeIso: '2026-11-06T07:08:00Z',
      totalCommitsCount: 55743,
      rawFilesById,
      longTermCommits: [],
      recentCommits: [],
    });

    // Verify Snapshot JSON contains ZERO IPv4 address strings
    const jsonString = JSON.stringify(snapshot);
    expect(/\d+\.\d+\.\d+\.\d+/.test(jsonString)).toBe(false);

    // Verify AES-256-GCM encryption & round-trip decryption
    const passkey = 'NTNU-Exec-2026-Secret!';
    const encrypted = encryptSnapshotPayload(snapshot, passkey);
    expect(encrypted.encrypted).toBe(true);
    expect(encrypted.ciphertext).not.toContain('55743');

    const decrypted = decryptSnapshotPayloadNode<typeof snapshot>(
      encrypted,
      passkey
    );
    expect(decrypted.totalCommitsCount).toBe(55743);
    expect(decrypted.uniqueExternalBlockIPv4).toBe(2);

    expect(() =>
      decryptSnapshotPayloadNode(encrypted, 'wrong-passkey')
    ).toThrow();
  });
});
